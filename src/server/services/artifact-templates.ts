export function renderArtifact(type: string, d: TemplateData): string {
  switch (type) {
    case "diagram-mermaid":
      return `%% ${d.project.name} — architecture revision v${d.revision.version} (${d.revision.id})\n%% Generated by DataBrain at ${d.generatedAt}. Generated, not validated.\n${toMermaid(d.revision.diagram)}`;
    case "diagram-drawio":
      return toDrawio(d.revision.diagram, `${d.project.name} v${d.revision.version}`);
    case "diagram-reactflow":
      return JSON.stringify({ projectId: d.project.id, architectureRevisionId: d.revision.id, version: d.revision.version, generatedAt: d.generatedAt, status: "generated-not-validated", diagram: d.revision.diagram }, null, 2) + "\n";
    case "blueprint-json":
      return (
        JSON.stringify(
          {
            schemaVersion: 1,
            status: "generated-not-validated",
            generatedAt: d.generatedAt,
            generator: d.generator,
            project: { id: d.project.id, name: d.project.name, description: d.project.description },
            architectureRevision: { id: d.revision.id, version: d.revision.version, title: d.revision.title, label: d.revision.label, contentHash: d.revision.contentHash, approvedAt: d.revision.approvedAt },
            requirements: d.requirements.map((r) => ({ field: r.field, state: r.state, value: r.value, kind: r.kind, origin: r.origin, evidence: r.evidence })),
            sections: d.revision.sections,
            diagram: d.revision.diagram,
            decisions: d.decisions.map((a) => ({ number: a.number, title: a.title, status: a.status, context: a.context, decision: a.decision, alternatives: a.alternatives, consequences: a.consequences })),
            knowledge: d.knowledge,
            sources: d.sources,
          },
          null,
          2,
        ) + "\n"
      );
    case "executive-summary":
      return doc(d, "Executive summary", ["executive-summary", "selected-option", "risks"]);
    case "hld":
      return `${header(d, "High-level design")}\n${sections(d, ["executive-summary", "context-requirements", "selected-option", "l0-context", "l1-logical"])}\n\n## Architecture diagram\n\n\`\`\`mermaid\n${toMermaid(d.revision.diagram)}\`\`\`\n\n${sections(d, ["data-flows", "identity-security", "governance", "sizing-cost", "risks", "sources"])}\n\n${footer(d)}`;
    case "lld":
      return doc(d, "Low-level design", ["l2-components", "l3-deployment", "data-flows", "network-dns", "identity-security", "devops-iac", "monitoring-dr"]);
    case "adr":
      return adrDoc(d);
    case "security-design":
      return doc(d, "Security design", ["identity-security", "network-dns", "governance"]);
    case "runbook":
      return `${header(d, "Operations runbook")}\n${sections(d, ["monitoring-dr", "rollback"])}\n\n## Routine operations\n\n| Task | Frequency | Owner | Procedure |\n|---|---|---|---|\n| Check pipeline run status | TODO | TODO | TODO |\n| Review failed loads | TODO | TODO | TODO |\n| Review access changes | TODO | TODO | TODO |\n| Test restore from backup | TODO | TODO | TODO |\n\n## Incident contacts\n\n- On-call rota: PLACEHOLDER\n- Escalation path: PLACEHOLDER\n\n${footer(d)}`;
    case "iac":
      return terraform(d);
    case "pipeline":
      return pipeline(d);
    case "sql-scaffold":
      return sql(d);
    case "migration-plan":
      return migrationPlan(d);
    case "test-plan":
      return testPlan(d);
    case "cutover-rollback":
      return cutover(d);
    default:
      throw new Error(`Unknown artifact type: ${type}`);
  }
}
