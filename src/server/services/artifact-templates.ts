import { TEMPLATE_VERSION } from "@/lib/artifact-catalog";
import { CANDIDATE_LABELS, ORIGIN_LABELS } from "@/lib/catalog";
import { toDrawio, toMermaid } from "@/lib/diagram";
import { INTAKE_FIELDS } from "@/lib/intake";
import type { BlueprintSection } from "@/lib/types";
import { slugify } from "@/lib/utils";
import type { Decision, Revision } from "./blueprint";
import type { Project, Requirement } from "./projects";

export interface TemplateData {
  project: Project;
  requirements: Requirement[];
  revision: Revision;
  decisions: Decision[];
  knowledge: { id: string; title: string; type: string; status: string; slug: string }[];
  sources: { id: string; title: string; url: string | null; sourceType: string }[];
  generatedAt: string;
  generator: string;
}

const origin = (s: BlueprintSection) => `_${s.edited ? "Edited by a person" : ORIGIN_LABELS[s.origin].label}_`;

function header(d: TemplateData, title: string): string {
  const label = CANDIDATE_LABELS[d.revision.label as keyof typeof CANDIDATE_LABELS]?.label ?? d.revision.label;
  return `# ${title}\n\n| | |\n|---|---|\n| Project | ${d.project.name} (\`${d.project.id}\`) |\n| Architecture revision | v${d.revision.version} (\`${d.revision.id}\`) — ${label} |\n| Revision content hash | \`${d.revision.contentHash ?? "not approved"}\` |\n| Generated | ${d.generatedAt} by ${d.generator}, template ${TEMPLATE_VERSION} |\n| Status | **Generated — not validated.** Review before use. |\n`;
}

function sections(d: TemplateData, keys: string[]): string {
  return keys
    .map((key) => d.revision.sections.find((s) => s.key === key))
    .filter((s): s is BlueprintSection => !!s)
    .map((s) => `## ${s.title}\n\n${origin(s)}\n\n${s.body || "TODO: this section is empty."}`)
    .join("\n\n");
}

function footer(d: TemplateData): string {
  const assumptions = d.requirements.filter((r) => r.kind === "assumption" || r.state === "unknown");
  const lines = assumptions.map((r) => `- ${INTAKE_FIELDS.find((f) => f.key === r.field)?.label ?? r.field}: ${r.state === "unknown" ? "unknown" : `assumed “${r.value}”`}`);
  return `## Assumptions and unknowns\n\n${lines.length ? lines.join("\n") : "- None recorded."}\n\n## Source references\n\n${d.sources.length ? d.sources.map((s) => `- ${s.title}${s.url ? ` — ${s.url}` : ""} (${s.sourceType})`).join("\n") : "- No sources are cited by the knowledge this revision is based on."}\n`;
}

const doc = (d: TemplateData, title: string, keys: string[]) => `${header(d, title)}\n${sections(d, keys)}\n\n${footer(d)}`;

function adrDoc(d: TemplateData): string {
  const body = d.decisions.length
    ? d.decisions.map((a) => `## ADR-${a.number}: ${a.title}\n\n**Status:** ${a.status}\n\n### Context\n\n${a.context || "TODO"}\n\n### Decision\n\n${a.decision || "TODO"}\n\n### Alternatives considered\n\n${a.alternatives || "TODO"}\n\n### Consequences\n\n${a.consequences || "TODO"}`).join("\n\n")
    : "No decision records exist for this project yet. TODO: record the architecture decision.";
  return `${header(d, "Architecture decision records")}\n${body}\n`;
}

function cloudOf(d: TemplateData): "azure" | "aws" | "gcp" | null {
  const tokens = d.requirements.find((r) => r.field === "target_platform")?.tokens ?? [];
  if (tokens.some((t) => ["azure", "fabric", "synapse", "azure-ai"].includes(t))) return "azure";
  if (tokens.some((t) => ["aws", "redshift", "aws-lakehouse"].includes(t))) return "aws";
  if (tokens.some((t) => ["gcp", "bigquery"].includes(t))) return "gcp";
  return null;
}

const hcl = (text: string) => text.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, " ");

function terraform(d: TemplateData): string {
  const cloud = cloudOf(d);
  const provider = cloud === "azure" ? { name: "azurerm", source: "hashicorp/azurerm", block: 'provider "azurerm" {\n  features {}\n}' } : cloud === "aws" ? { name: "aws", source: "hashicorp/aws", block: 'provider "aws" {\n  region = var.location\n}' } : cloud === "gcp" ? { name: "google", source: "hashicorp/google", block: 'provider "google" {\n  region = var.location\n}' } : null;
  const components = d.revision.diagram.nodes.filter((n) => !["source", "consumer"].includes(n.kind));
  return `# Terraform starter for ${d.project.name}
# Generated by DataBrain (${d.generator}, template ${TEMPLATE_VERSION}) at ${d.generatedAt}
# Project ${d.project.id} · architecture revision v${d.revision.version} (${d.revision.id})
#
# STATUS: generated, not validated. This file declares NO resources.
# It gives you variables, tags and the component inventory from the approved diagram.
# Add one resource or module per component below, choosing resource types, SKUs and
# network ranges from your own environment. DataBrain does not invent those values.

terraform {
  required_version = ">= 1.5.0"
${provider ? `  required_providers {\n    ${provider.name} = {\n      source = "${provider.source}"\n      # TODO: pin a provider version you have tested.\n    }\n  }\n` : "  # TODO: the target cloud is not stated in the requirements. Add required_providers.\n"}}
${provider ? `\n${provider.block}\n` : ""}
variable "environment" {
  description = "Environment name, for example dev, test or prod."
  type        = string
}

variable "location" {
  description = "Region to deploy to. PLACEHOLDER: no default is set on purpose."
  type        = string
}

variable "name_prefix" {
  description = "Prefix for resource names. PLACEHOLDER: follow your naming convention."
  type        = string
}

locals {
  tags = {
    project               = "${hcl(slugify(d.project.name))}"
    environment           = var.environment
    architecture_revision = "v${d.revision.version}"
    managed_by            = "terraform"
  }

  # Component inventory from the approved architecture diagram.
  components = {
${components.map((n) => `    "${hcl(n.id)}" = {\n      label      = "${hcl(n.label)}"\n      kind       = "${n.kind}"\n      technology = "${hcl(n.technology ?? "TODO")}"\n    }`).join("\n")}
  }
}

${components.map((n) => `# TODO(${n.id}): add the resource or module for "${hcl(n.label)}"${n.technology ? ` (${hcl(n.technology)})` : ""}.`).join("\n")}

output "components" {
  description = "Components this configuration is expected to provision."
  value       = local.components
}
`;
}

function pipeline(d: TemplateData): string {
  return `# CI validation for ${d.project.name}
# Generated by DataBrain (template ${TEMPLATE_VERSION}) for architecture revision v${d.revision.version} (${d.revision.id}).
# STATUS: generated, not validated. This workflow only formats and validates the IaC.
# It contains no plan or apply step and needs no cloud credentials.
name: validate-infrastructure

on:
  pull_request:
    paths:
      - "iac/**"
  workflow_dispatch: {}

permissions:
  contents: read

jobs:
  validate:
    runs-on: ubuntu-latest
    defaults:
      run:
        working-directory: iac
    steps:
      # TODO: pin these actions to the versions your organisation has approved.
      - uses: actions/checkout@v4
      - uses: hashicorp/setup-terraform@v3
      - name: Check formatting
        run: terraform fmt -check -recursive
      - name: Initialise without a backend
        run: terraform init -backend=false
      - name: Validate
        run: terraform validate
`;
}

